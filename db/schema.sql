-- Cockatoo Marine schema for Postgres (Supabase).
-- Ported from the original SQLite schema: same tables, columns and rules.
-- Dates and timestamps stay ISO-8601 text so existing comparisons keep working.
-- Double bookings are still blocked by a trigger, so no code path can create an overlapping allocation.

CREATE OR REPLACE FUNCTION public.now_iso() RETURNS text
LANGUAGE sql STABLE SET search_path = '' AS
$$ SELECT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"') $$;

CREATE TABLE IF NOT EXISTS settings (key text PRIMARY KEY, value text, placeholder integer DEFAULT 0);

CREATE TABLE IF NOT EXISTS customers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, kind text DEFAULT 'individual' CHECK (kind IN ('individual','company')),
  name text NOT NULL, company text, email text, phone text, address text, billing_address text, abn text,
  id_notes text, source text, tags text, notes text, created_at text DEFAULT public.now_iso());

CREATE TABLE IF NOT EXISTS users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email text UNIQUE NOT NULL, name text,
  role text NOT NULL CHECK (role IN ('admin','office','yard','finance','customer')),
  password_hash text, customer_id integer, totp_enabled integer DEFAULT 0, created_at text DEFAULT public.now_iso());

CREATE TABLE IF NOT EXISTS boats (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id integer REFERENCES customers(id), name text, type text, make_model text,
  length_m double precision NOT NULL, hin text, rego text, engine text, trailer integer DEFAULT 0, trailer_details text,
  insurer text, insurance_policy text, insurance_expiry text, photo text, docs text DEFAULT '[]', qr_token text UNIQUE,
  created_at text DEFAULT public.now_iso());

CREATE TABLE IF NOT EXISTS bays (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code text UNIQUE NOT NULL, zone text, max_length_m double precision NOT NULL,
  status text DEFAULT 'available' CHECK (status IN ('available','occupied','reserved','maintenance','out_of_service')), notes text);

CREATE TABLE IF NOT EXISTS rates (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, min_len double precision NOT NULL, max_len double precision NOT NULL,
  package text NOT NULL CHECK (package IN ('standard','unlimited')), term text NOT NULL CHECK (term IN ('annual','monthly')),
  monthly_rate double precision NOT NULL, placeholder integer DEFAULT 1);

CREATE TABLE IF NOT EXISTS leads (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id integer REFERENCES customers(id), name text, email text, phone text,
  service text DEFAULT 'storage', source text DEFAULT 'website', stage text DEFAULT 'new'
    CHECK (stage IN ('new','contacted','quoted','deposit_pending','booked','lost')),
  lost_reason text, message text, quote_json text, assigned_to integer, created_at text DEFAULT public.now_iso(), updated_at text);

CREATE TABLE IF NOT EXISTS bookings (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ref text UNIQUE, kind text DEFAULT 'storage' CHECK (kind IN ('storage','maintenance')),
  bay_id integer NOT NULL REFERENCES bays(id), customer_id integer REFERENCES customers(id), boat_id integer REFERENCES boats(id),
  lead_id integer, package text, term text, monthly_rate double precision,
  start_date text NOT NULL, end_date text NOT NULL,
  status text NOT NULL CHECK (status IN ('hold','pending','confirmed','active','maintenance','completed','cancelled','expired')),
  hold_expires_at text, pending_expires_at text, deposit_amount double precision, deposit_paid integer DEFAULT 0,
  stripe_session_id text, notes text, created_by integer, created_at text DEFAULT public.now_iso(),
  CHECK (end_date > start_date));

-- Blocks overlapping active allocations of a bay. The advisory lock serialises
-- concurrent writes for the same bay, so two simultaneous requests cannot both pass the check.
CREATE OR REPLACE FUNCTION public.bookings_no_overlap() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  IF NEW.status IN ('hold','pending','confirmed','active','maintenance') THEN
    PERFORM pg_advisory_xact_lock(72001, NEW.bay_id);
    IF EXISTS (
      SELECT 1 FROM public.bookings b
      WHERE b.bay_id = NEW.bay_id AND b.id IS DISTINCT FROM NEW.id
        AND b.status IN ('hold','pending','confirmed','active','maintenance')
        AND (b.status <> 'hold' OR b.hold_expires_at > public.now_iso())
        AND b.start_date < NEW.end_date AND NEW.start_date < b.end_date) THEN
      RAISE EXCEPTION 'DOUBLE_BOOKING';
    END IF;
  END IF;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS bookings_no_overlap_ins ON bookings;
CREATE TRIGGER bookings_no_overlap_ins BEFORE INSERT ON bookings
  FOR EACH ROW EXECUTE FUNCTION public.bookings_no_overlap();
DROP TRIGGER IF EXISTS bookings_no_overlap_upd ON bookings;
CREATE TRIGGER bookings_no_overlap_upd BEFORE UPDATE OF bay_id, start_date, end_date, status ON bookings
  FOR EACH ROW EXECUTE FUNCTION public.bookings_no_overlap();

CREATE TABLE IF NOT EXISTS contracts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, booking_id integer REFERENCES bookings(id), customer_id integer REFERENCES customers(id),
  term text, package text, monthly_rate double precision, start_date text, end_date text, tc_version text, tc_accepted_at text,
  status text DEFAULT 'active', created_at text DEFAULT public.now_iso());

CREATE TABLE IF NOT EXISTS invoices (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, number text UNIQUE, customer_id integer REFERENCES customers(id), booking_id integer,
  period text, issue_date text, due_date text, subtotal_ex double precision, gst double precision, total double precision, paid double precision DEFAULT 0,
  status text DEFAULT 'issued' CHECK (status IN ('draft','issued','paid','overdue','void')), kind text DEFAULT 'storage',
  created_at text DEFAULT public.now_iso());

CREATE TABLE IF NOT EXISTS invoice_lines (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, invoice_id integer REFERENCES invoices(id), description text, category text, billing text,
  qty double precision DEFAULT 1, unit_inc double precision, amount_inc double precision, gst double precision);

CREATE TABLE IF NOT EXISTS payments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id integer, booking_id integer, invoice_id integer, amount double precision NOT NULL,
  method text CHECK (method IN ('stripe','bank_transfer','card_phone','cash')), reference text, paid_on text,
  kind text DEFAULT 'invoice', reconciled integer DEFAULT 0, recorded_by integer, created_at text DEFAULT public.now_iso());

CREATE TABLE IF NOT EXISTS extras (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, booking_id integer, customer_id integer, date text, description text, category text,
  amount_inc double precision, invoice_id integer, source_type text, source_id integer);

CREATE TABLE IF NOT EXISTS lifts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, booking_id integer REFERENCES bookings(id), boat_id integer, date text NOT NULL, slot text NOT NULL,
  status text DEFAULT 'booked' CHECK (status IN ('booked','done','cancelled','no_show')), is_extra integer DEFAULT 0,
  transfer integer DEFAULT 1, wash integer DEFAULT 1, engine_flush integer DEFAULT 0, notes text,
  booked_via text DEFAULT 'staff', created_by integer, created_at text DEFAULT public.now_iso());

CREATE TABLE IF NOT EXISTS checklist_templates (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text, type text CHECK (type IN ('checkin','release','return')), items text, active integer DEFAULT 1);

CREATE TABLE IF NOT EXISTS checklists (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, type text, template_id integer, boat_id integer REFERENCES boats(id), booking_id integer, customer_id integer,
  staff_id integer, results text, inventory text, fuel_level text, damage_notes text, photos text DEFAULT '[]',
  signature text, signed_name text, released_to text, release_id integer, created_at text DEFAULT public.now_iso());

CREATE TABLE IF NOT EXISTS service_jobs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id integer, boat_id integer, service text, description text, quote_amount double precision,
  scheduled_date text, assigned_to integer, parts text, parts_cost double precision DEFAULT 0, labour_hours double precision DEFAULT 0, labour_rate double precision DEFAULT 0,
  status text DEFAULT 'quoted' CHECK (status IN ('quoted','scheduled','in_progress','done','invoiced','cancelled')),
  photos text DEFAULT '[]', created_at text DEFAULT public.now_iso());

CREATE TABLE IF NOT EXISTS assets (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text, type text CHECK (type IN ('bay','equipment','facility')), bay_id integer, notes text);

CREATE TABLE IF NOT EXISTS maintenance_jobs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, asset_id integer REFERENCES assets(id), title text, kind text CHECK (kind IN ('scheduled','reactive')),
  due_date text, recur_days integer, status text DEFAULT 'open' CHECK (status IN ('open','in_progress','done')),
  assigned_to integer, notes text, cost double precision, block_booking_id integer, completed_at text, created_at text DEFAULT public.now_iso());

CREATE TABLE IF NOT EXISTS expenses (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, date text, category text, supplier text, description text, amount_inc double precision, gst double precision, receipt text,
  created_at text DEFAULT public.now_iso());

CREATE TABLE IF NOT EXISTS watchlist (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text, email text, phone text, rego text, hin text, reason text, evidence text,
  added_by integer, created_at text DEFAULT public.now_iso(), updated_at text);

CREATE TABLE IF NOT EXISTS watch_alerts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, watch_id integer, entity text, entity_id integer, detail text, resolved integer DEFAULT 0,
  created_at text DEFAULT public.now_iso());

CREATE TABLE IF NOT EXISTS communications (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id integer, lead_id integer, channel text, direction text, summary text, user_id integer,
  created_at text DEFAULT public.now_iso());

CREATE TABLE IF NOT EXISTS email_templates (key text PRIMARY KEY, subject text, body text);

CREATE TABLE IF NOT EXISTS outbox (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, channel text DEFAULT 'email', recipient text, subject text, body text, template text,
  dedupe_key text UNIQUE, customer_id integer, created_at text DEFAULT public.now_iso());

CREATE TABLE IF NOT EXISTS audit_log (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id integer, user_name text, action text, entity text, entity_id integer, reason text,
  detail text, at text DEFAULT public.now_iso());

