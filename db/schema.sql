-- The app talks to Postgres directly from the server. Row level security with no policies
-- keeps every table closed to Supabase's public Data API (anon / authenticated keys).
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['settings','customers','users','boats','bays','rates','leads','bookings','contracts','invoices',
    'invoice_lines','payments','extras','lifts','checklist_templates','checklists','service_jobs','assets','maintenance_jobs',
    'expenses','watchlist','watch_alerts','communications','email_templates','outbox','audit_log','integrations','devices','files']
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
  END LOOP;
END $$;

-- Internal app state (session signing secret, last scheduled-job run). Not shown in the admin settings page.
CREATE TABLE IF NOT EXISTS app_state (key text PRIMARY KEY, value text);
ALTER TABLE public.app_state ENABLE ROW LEVEL SECURITY;
